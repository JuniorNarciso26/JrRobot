import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const header = readFileSync(new URL('../../firmware/module_portal/jr_portal_v16.h', import.meta.url), 'utf8');
const chunks = header.split('\n').filter(l=>l.startsWith('"')).map(l=>JSON.parse(l.endsWith(';')?l.slice(0,-1):l));
const full = chunks.join('');
new vm.Script(full);
const code = chunks.filter(s=>/^(function memKb|function showMemorySnapshot|async function captureLiveMemory|async function rtcHandleSignal|async function startLive)/.test(s)).join('');
const events=[], elements=new Map();
const q=id=>{if(!elements.has(id))elements.set(id,{textContent:'',classList:{add(){},remove(){}}});return elements.get(id);};
const sample='heap_internal_free=86000 heap_internal_largest=31000 heap_internal_min=14000 heap_psram_free=7700000 heap_psram_largest=7600000';
const ctx=vm.createContext({console,AbortSignal,Date,Number,Object,Error,fetch:async()=>({ok:true,text:async()=>sample}),q,liveLogAdd:x=>events.push(x),live:false,liveStarting:false,liveSeq:0,liveFrames:0,liveStarted:0,performance:{now:()=>1},liveProfile:()=>({id:'balanced',size:'VGA',fps:10,quality:14}),liveStatReset:()=>events.length=0,rtcPost:async()=>events.push('POST'),startWebRtc:async()=>events.push('START'),cameraRotationLabel:()=>0,setState(){},feedback(){}});
vm.runInContext(code,ctx);
await ctx.startLive();
assert(events[0].includes('stage=before_click'));
assert.equal(events[1],'POST');
assert.equal(events.at(-1),'START');
assert(q('v16-memory-before').textContent.includes('84.0 KB'));
await ctx.rtcHandleSignal({type:'memory',message:'stage=task_mic result=ESP_ERR_NO_MEM internal_free=34000 internal_largest=6000 internal_min=4000 psram_free=7000000 psram_largest=6900000'});
assert(events.at(-1).includes('stage=task_mic result=ESP_ERR_NO_MEM'));
assert(q('v16-memory-after').textContent.includes('task_mic'));
await ctx.rtcHandleSignal({type:'memory',message:'stage=after_session result=ESP_OK internal_free=20000 internal_largest=10000 internal_min=4000 psram_free=7000000 psram_largest=6900000'});
assert(events.at(-1).includes('stage=after_session result=ESP_OK'));
ctx.fetch=async()=>{throw Error('offline');};
await ctx.captureLiveMemory('before_click');
assert(events.at(-1).includes('MEM_SNAPSHOT_ERROR'));
ctx.live=false;
ctx.startWebRtc=async()=>{throw Error('permission');};
await ctx.startLive();
assert(events.some(e=>e.includes('stage=after_start_error')));
assert.equal(ctx.live,false);
console.log('PASS panel syntax, before-start ordering, failure/success snapshots, failed diagnostics and start exception');
